create or replace function public.force_pending_status()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.status := 'pending';
  if new.author_name is not null then
    new.author_name := nullif(left(btrim(new.author_name), 40), '');
  end if;
  new.body := btrim(new.body);
  return new;
end;
$$;

