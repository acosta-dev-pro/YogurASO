-- A lo sumo 3 envíos cada 10 minutos por visitante (preguntas y comentarios por separado).
-- security definer: sin él, el conteo corre con la RLS de anon y solo ve filas aprobadas,
-- así que el límite nunca saltaba con las pendientes.
create or replace function public.reject_interaction_spam()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  n int;
begin
  if tg_table_name = 'faq_questions' then
    select count(*) into n
      from public.faq_questions
     where visitor_id = new.visitor_id
       and created_at > now() - interval '10 minutes';
  elsif tg_table_name = 'content_comments' then
    select count(*) into n
      from public.content_comments
     where visitor_id = new.visitor_id
       and created_at > now() - interval '10 minutes';
  else
    return new;
  end if;
  if n >= 3 then
    raise exception 'Demasiados envíos seguidos. Espera un momento.'
      using errcode = 'P0001';
  end if;
  return new;
end;
$$;

drop trigger if exists trg_faq_questions_spam on public.faq_questions;
create trigger trg_faq_questions_spam
  before insert on public.faq_questions
  for each row execute function public.reject_interaction_spam();

drop trigger if exists trg_content_comments_spam on public.content_comments;
create trigger trg_content_comments_spam
