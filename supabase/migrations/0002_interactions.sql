drop function if exists public.list_faq_questions(uuid);
create function public.list_faq_questions(p_visitor_id uuid)
returns table (
  id          bigint,
  author_name text,
  body        text,
  status      text,
  created_at  timestamptz,
  mine        boolean
)
language sql
stable
security definer
set search_path = ''
as $$
  select q.id, q.author_name, q.body, q.status, q.created_at,
         (q.visitor_id = p_visitor_id)
    from public.faq_questions q
   where q.status = 'approved'
      or q.visitor_id = p_visitor_id
   order by q.created_at desc
   limit 50;
$$;

drop function if exists public.list_post_comments(text, uuid);
create function public.list_post_comments(
  p_target_id  text,
  p_visitor_id uuid
)
returns table (
  id          bigint,
  author_name text,
  body        text,
  status      text,
  created_at  timestamptz,
  mine        boolean
)
language sql
stable
security definer
set search_path = ''
as $$
  select c.id, c.author_name, c.body, c.status, c.created_at,
         (c.visitor_id = p_visitor_id)
    from public.content_comments c
   where c.target_type = 'post'
     and c.target_id = p_target_id
     and (c.status = 'approved' or c.visitor_id = p_visitor_id)
   order by c.created_at asc
   limit 80;
$$;

create or replace function public.like_state(
  p_target_type text,
  p_target_id   text,
  p_visitor_id  uuid
)
returns table (
  likes int,
  liked boolean
)
language plpgsql
stable
security definer
set search_path = ''
as $$
begin
  if p_target_type not in ('post', 'product')
     or p_target_id is null
     or char_length(btrim(p_target_id)) not between 1 and 80
     or p_visitor_id is null then
    raise exception 'Consulta de me gusta inválida' using errcode = '22023';
  end if;
  return query
  select count(*)::int,
         exists (
           select 1 from public.content_likes l
            where l.target_type = p_target_type
              and l.target_id = p_target_id
              and l.visitor_id = p_visitor_id
         )
    from public.content_likes l
   where l.target_type = p_target_type
     and l.target_id = p_target_id;
end;
$$;

create or replace function public.toggle_like(
  p_target_type text,
  p_target_id   text,
  p_visitor_id  uuid
)
returns table (
  likes int,
  liked boolean
)
language plpgsql
security definer
set search_path = ''
as $$
declare
  existed boolean;
begin
  if p_target_type not in ('post', 'product')
     or p_target_id is null
     or char_length(btrim(p_target_id)) not between 1 and 80
     or p_visitor_id is null then
    raise exception 'Me gusta inválido' using errcode = '22023';
  end if;

  delete from public.content_likes l
   where l.target_type = p_target_type
     and l.target_id = p_target_id
     and l.visitor_id = p_visitor_id
  returning true into existed;

  if existed is not true then
    insert into public.content_likes (target_type, target_id, visitor_id)
    values (p_target_type, btrim(p_target_id), p_visitor_id);
  end if;

  return query
  select * from public.like_state(p_target_type, p_target_id, p_visitor_id);
end;
$$;

