-- Preguntas frecuentes, me gusta y comentarios de los visitantes.
-- Las filas nuevas quedan en revisión (status = 'pending').

-- ---------------------------------------------------------------------
-- Preguntas del FAQ
-- ---------------------------------------------------------------------
create table if not exists public.faq_questions (
  id           bigint generated by default as identity primary key,
  visitor_id   uuid not null,
  author_name  text,
  body         text not null,
  status       text not null default 'pending'
               check (status in ('pending', 'approved', 'hidden')),
  created_at   timestamptz not null default now(),
  constraint faq_questions_name_len check (author_name is null or char_length(author_name) between 1 and 40),
  constraint faq_questions_body_len check (char_length(body) between 8 and 500)
);

comment on table public.faq_questions is 'Preguntas enviadas desde el home. pending hasta que alguien las apruebe.';

create index if not exists idx_faq_questions_status on public.faq_questions (status, created_at desc);
create index if not exists idx_faq_questions_visitor on public.faq_questions (visitor_id, created_at desc);

-- ---------------------------------------------------------------------
-- Me gusta (post de Instagram "nosotros" y productos)
-- target_type: post | product
-- target_id:   'nosotros' para el post, o el id del producto (texto)
-- ---------------------------------------------------------------------
create table if not exists public.content_likes (
  id           bigint generated by default as identity primary key,
  target_type  text not null check (target_type in ('post', 'product')),
  target_id    text not null check (char_length(btrim(target_id)) between 1 and 80),
  visitor_id   uuid not null,
  created_at   timestamptz not null default now(),
  unique (target_type, target_id, visitor_id)
);

comment on table public.content_likes is 'Un me gusta por visitante y objetivo. El visitante es un uuid en localStorage, no una cuenta.';

create index if not exists idx_content_likes_target on public.content_likes (target_type, target_id);

-- ---------------------------------------------------------------------
-- Comentarios del post (y, si hace falta, el mismo molde)
-- ---------------------------------------------------------------------
create table if not exists public.content_comments (
  id           bigint generated by default as identity primary key,
  target_type  text not null check (target_type in ('post')),
  target_id    text not null check (char_length(btrim(target_id)) between 1 and 80),
  visitor_id   uuid not null,
  author_name  text,
  body         text not null,
  status       text not null default 'pending'
               check (status in ('pending', 'approved', 'hidden')),
  created_at   timestamptz not null default now(),
  constraint content_comments_name_len check (author_name is null or char_length(author_name) between 1 and 40),
  constraint content_comments_body_len check (char_length(body) between 2 and 400)
);

comment on table public.content_comments is 'Comentarios del post. pending hasta aprobarlos.';

create index if not exists idx_content_comments_target on public.content_comments (target_type, target_id, status, created_at desc);
create index if not exists idx_content_comments_visitor on public.content_comments (visitor_id, created_at desc);

-- ---------------------------------------------------------------------
-- El cliente no elige el estado: siempre entra en revisión.
-- ---------------------------------------------------------------------
create or replace function public.force_pending_status()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.status := 'pending';
  if new.author_name is not null then
    new.author_name := nullif(left(btrim(new.author_name), 40), '');
  end if;
  new.body := btrim(new.body);
  return new;
end;
$$;

drop trigger if exists trg_faq_questions_pending on public.faq_questions;
create trigger trg_faq_questions_pending
  before insert on public.faq_questions
  for each row execute function public.force_pending_status();

drop trigger if exists trg_content_comments_pending on public.content_comments;
create trigger trg_content_comments_pending
  before insert on public.content_comments
  for each row execute function public.force_pending_status();

-- A lo sumo 3 envíos cada 10 minutos por visitante (preguntas y comentarios por separado).
-- security definer: sin él, el conteo corre con la RLS de anon y solo ve filas aprobadas,
-- así que el límite nunca saltaba con las pendientes.
create or replace function public.reject_interaction_spam()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  n int;
begin
  if tg_table_name = 'faq_questions' then
    select count(*) into n
      from public.faq_questions
     where visitor_id = new.visitor_id
       and created_at > now() - interval '10 minutes';
  elsif tg_table_name = 'content_comments' then
    select count(*) into n
      from public.content_comments
     where visitor_id = new.visitor_id
       and created_at > now() - interval '10 minutes';
  else
    return new;
  end if;
  if n >= 3 then
    raise exception 'Demasiados envíos seguidos. Espera un momento.'
      using errcode = 'P0001';
  end if;
  return new;
end;
$$;

drop trigger if exists trg_faq_questions_spam on public.faq_questions;
create trigger trg_faq_questions_spam
  before insert on public.faq_questions
  for each row execute function public.reject_interaction_spam();

drop trigger if exists trg_content_comments_spam on public.content_comments;
create trigger trg_content_comments_spam
  before insert on public.content_comments
  for each row execute function public.reject_interaction_spam();

