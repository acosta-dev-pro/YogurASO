alter table public.faq_questions    enable row level security;
alter table public.content_likes    enable row level security;
alter table public.content_comments enable row level security;

drop policy if exists "faq_questions: ver aprobadas" on public.faq_questions;
create policy "faq_questions: ver aprobadas"
  on public.faq_questions for select to anon, authenticated
  using (status = 'approved');

drop policy if exists "faq_questions: enviar" on public.faq_questions;
create policy "faq_questions: enviar"
  on public.faq_questions for insert to anon, authenticated
  with check (
    status = 'pending'
    and visitor_id is not null
    and char_length(body) between 8 and 500
  );

drop policy if exists "content_comments: ver aprobados" on public.content_comments;
create policy "content_comments: ver aprobados"
  on public.content_comments for select to anon, authenticated
  using (status = 'approved');

drop policy if exists "content_comments: enviar" on public.content_comments;
create policy "content_comments: enviar"
  on public.content_comments for insert to anon, authenticated
  with check (
    status = 'pending'
    and target_type = 'post'
    and visitor_id is not null
    and char_length(body) between 2 and 400
  );

-- Sin policy de select: los conteos salen de like_state / toggle_like.
drop policy if exists "content_likes: dar me gusta" on public.content_likes;
create policy "content_likes: dar me gusta"
  on public.content_likes for insert to anon, authenticated
  with check (
    target_type in ('post', 'product')
    and visitor_id is not null
    and char_length(target_id) between 1 and 80
  );

grant select, insert on public.faq_questions to anon, authenticated;
